// Parses ../02-curriculum-map.md into the site's seed data.
// Outputs:
//   src/content/curriculum.generated.json  (read by the Next.js app)
//   supabase/seed.sql                       (curriculum rows for Supabase)
//
// Run: npm run curriculum

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "..", "02-curriculum-map.md");
const jsonOut = resolve(root, "src/content/curriculum.generated.json");
const sqlOut = resolve(root, "supabase/seed.sql");

const pad = (n) => String(n).padStart(2, "0");

const clean = (s) => {
  const text = s
    .replace(/\*\*/g, "")
    .replace(/^\*|\*$/g, "")
    .trim();
  return text.charAt(0).toUpperCase() + text.slice(1);
};

function parseTrack(raw) {
  let text = raw.trim();
  let kind = "cinematic";
  if (text.startsWith("🖥️")) {
    kind = "screen";
    text = text.slice("🖥️".length).trim();
  } else if (text.startsWith("🎬")) {
    text = text.slice("🎬".length).trim();
  }

  let story = null;
  const storyMatch = text.match(/\*\(([^)]+)\)\*\s*$/);
  if (storyMatch) {
    story = storyMatch[1].trim();
    text = text.slice(0, storyMatch.index).trim();
  }
  return { title: clean(text), kind, story };
}

function parse(md) {
  const lines = md.split(/\r?\n/);
  const pillars = [];
  let pillar = null;
  let mod = null;

  for (const line of lines) {
    if (line.startsWith("## Track count summary")) break;

    const p = line.match(/^## PILLAR (\d+): (.+?) \((\d+) tracks\)/);
    if (p) {
      pillar = { number: Number(p[1]), heading: p[2], coreQuestion: "", deliverable: "", modules: [] };
      pillars.push(pillar);
      mod = null;
      continue;
    }
    if (!pillar) continue;

    const q = line.match(/^\*Core question: (.+)\*$/);
    if (q) {
      pillar.coreQuestion = q[1].trim();
      continue;
    }

    const m = line.match(/^### Module (\d+): (.+?)\s*(🆓)?\s*\((\d+)\)\s*$/);
    if (m) {
      mod = { number: Number(m[1]), title: clean(m[2]), isFree: Boolean(m[3]), deliverable: "", tracks: [] };
      pillar.modules.push(mod);
      continue;
    }
    if (!mod) continue;

    const t = line.match(/^\d+\.\s+(.+)$/);
    if (t) {
      mod.tracks.push(parseTrack(t[1]));
      continue;
    }

    if (line.startsWith("📦")) {
      const body = line.slice("📦".length).trim();
      const pillarDeliverable = body.match(/^\*\*Pillar deliverable: (.+?)\*\*\s*(.*)$/);
      if (pillarDeliverable) {
        pillar.deliverable = clean(`${pillarDeliverable[1]} ${pillarDeliverable[2]}`);
        if (!mod.deliverable) mod.deliverable = clean(pillarDeliverable[1]);
      } else {
        mod.deliverable = clean(body);
      }
      continue;
    }

    // Pillar 8 lists its tracks inline, separated by " · ".
    if (line.includes(" · ") && mod.tracks.length === 0) {
      for (const part of line.split(" · ")) mod.tracks.push(parseTrack(part));
    }
  }
  return pillars;
}

function toRows(pillars) {
  return pillars.map((p) => ({
    number: p.number,
    coreQuestion: p.coreQuestion,
    deliverable: p.deliverable,
    modules: p.modules.map((m) => ({
      number: m.number,
      title: m.title,
      isFree: m.isFree,
      deliverable: m.deliverable,
      tracks: m.tracks.map((t, i) => ({
        number: i + 1,
        code: `${pad(m.number)}.${pad(i + 1)}`,
        slug: `${pad(m.number)}-${pad(i + 1)}`,
        title: t.title,
        kind: t.kind,
        story: t.story,
      })),
    })),
  }));
}

const sql = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

function toSeedSql(pillars) {
  const out = [
    "-- Generated by scripts/build-curriculum.mjs from 02-curriculum-map.md. Do not edit by hand.",
    "-- Pillar names/colours live in src/content/pillars.ts and are upserted here by number.",
    "begin;",
    "delete from tracks; delete from modules;",
  ];
  for (const p of pillars) {
    out.push(
      `update pillars set core_question = ${sql(p.coreQuestion)}, deliverable = ${sql(p.deliverable)} where number = ${p.number};`,
    );
    for (const m of p.modules) {
      out.push(
        `insert into modules (pillar_id, number, title, is_free, deliverable_title) select id, ${m.number}, ${sql(m.title)}, ${m.isFree}, ${sql(m.deliverable)} from pillars where number = ${p.number};`,
      );
      for (const t of m.tracks) {
        out.push(
          `insert into tracks (module_id, number, slug, title, kind, story) select m.id, ${t.number}, ${sql(t.slug)}, ${sql(t.title)}, ${sql(t.kind)}, ${sql(t.story)} from modules m join pillars p on p.id = m.pillar_id where p.number = ${p.number} and m.number = ${m.number};`,
        );
      }
    }
  }
  out.push("commit;", "");
  return out.join("\n");
}

const pillars = toRows(parse(readFileSync(source, "utf8")));
writeFileSync(jsonOut, JSON.stringify(pillars, null, 2) + "\n");
writeFileSync(sqlOut, toSeedSql(pillars));

const trackCount = pillars.reduce((n, p) => n + p.modules.reduce((k, m) => k + m.tracks.length, 0), 0);
console.log(`Parsed ${pillars.length} pillars, ${pillars.reduce((n, p) => n + p.modules.length, 0)} modules, ${trackCount} tracks.`);
for (const p of pillars) {
  console.log(`  P${p.number}: ${p.modules.length} modules, ${p.modules.reduce((k, m) => k + m.tracks.length, 0)} tracks`);
}
