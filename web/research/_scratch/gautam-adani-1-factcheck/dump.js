const fs=require('fs');
const b=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
let o=[];
const s=c=>' ['+(c||[]).join(',')+']';
o.push('SLUG '+b.slug,'NAME '+b.name,'TITLE '+b.title,'SUB '+b.subtitle,'HOOK '+b.hook+s(b.hookSrc));
o.push('PORTRAIT '+JSON.stringify(b.portrait));
(b.photos||[]).forEach((p,i)=>o.push('PHOTO'+i+' '+JSON.stringify(p)));
b.glance.forEach((g,i)=>o.push('GL'+i+' '+g.label+': '+g.value+s(g.src)));
o.push('HOW '+b.contact.howToReach);
b.contact.channels.forEach((c,i)=>o.push('CH'+i+' '+JSON.stringify(c)));
b.contact.socials.forEach((c,i)=>o.push('SOC'+i+' '+JSON.stringify(c)));
b.chapters.forEach((c,ci)=>{o.push('\n## C'+ci+' '+c.id+' | '+c.kicker+' | '+c.title);
 c.blocks.forEach((x,i)=>{let t=ci+'.'+i+' '+x.t+': ';
  if(x.t=='p'||x.t=='example')t+=x.text+s(x.src);
  else if(x.t=='h'||x.t=='note')t+=x.text;
  else if(x.t=='quote')t+='"'+x.text+'" -- '+x.who+s(x.src);
  else if(x.t=='facts'||x.t=='timeline')t+=x.items.map(y=>(y.value||y.when)+' = '+(y.label||y.text)+s(y.src)).join(' || ');
  else if(x.t=='photo')t+=JSON.stringify(x.photo);
  else if(x.t=='venture')t+=x.name+' ('+x.years+') '+x.outcome+' IDEA:'+x.idea+' DECISION:'+x.decision+' STARTED:'+x.howStarted+' FUNDING:'+x.funding+' HAPPENED:'+x.whatHappened+' LESSON:'+x.lesson+s(x.src);
  else if(x.t=='lesson')t+=x.title+' :: '+x.text;
  o.push(t);});});
b.lessons.forEach((l,i)=>o.push('L'+i+' '+l.title+' :: '+l.text));
o.push('DISPUTED '+JSON.stringify(b.factCheck.disputed,null,0));
o.push('METHOD '+b.factCheck.method);
o.push('VERIFIED '+b.verifiedAt);
b.sources.forEach((c,i)=>o.push('S'+i+' '+c.label+' | '+c.url));
fs.writeFileSync(process.argv[3],o.join('\n'));
console.log(o.join('\n').length);
